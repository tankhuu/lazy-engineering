#!/usr/bin/env python3
"""Install ECC (github.com/affaan-m/ECC) into ./.claude and layer the platform pack on top.

Steps:
  1. Resolve an ECC checkout (ECC_HOME, Claude plugin cache, or a shallow clone).
  2. Run `install.sh --config ecc-install.json` with the tracked .claude/settings.json moved aside.
  3. Move ECC's generated hooks (they embed absolute local paths) into .claude/settings.local.json.
  4. Restore the tracked platform .claude/settings.json.
  5. Prune ECC agents/commands/skills/rules not listed in ecc-keep.json.
  6. Write .claude/.gitignore so ECC-managed files never get committed.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CLAUDE = REPO / ".claude"
ECC_REPO_URL = os.environ.get("ECC_REPO_URL", "https://github.com/affaan-m/ECC.git")
ECC_MARKER = "resolve-ecc-root"


def log(msg: str) -> None:
    print(f"[ecc-sync] {msg}")


def resolve_ecc_home() -> Path:
    env = os.environ.get("ECC_HOME")
    if env:
        return Path(env).expanduser().resolve()

    cache = Path.home() / ".claude" / "plugins" / "cache" / "ecc" / "ecc"
    if cache.is_dir():
        versions = sorted(
            (p for p in cache.iterdir() if (p / "install.sh").is_file()),
            key=lambda p: [int(x) if x.isdigit() else 0 for x in p.name.split(".")],
        )
        if versions:
            return versions[-1]

    clone = Path.home() / ".cache" / "ecc"
    if not (clone / "install.sh").is_file():
        cmd = ["git", "clone", "--depth", "1"]
        if os.environ.get("ECC_REF"):
            cmd += ["--branch", os.environ["ECC_REF"]]
        cmd += [ECC_REPO_URL, str(clone)]
        log(f"cloning {ECC_REPO_URL} -> {clone}")
        subprocess.run(cmd, check=True)
    return clone


def load_json(path: Path, default):
    if not path.is_file():
        return default
    return json.loads(path.read_text())


def write_json(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2) + "\n")


def is_ecc_hook(entry: dict) -> bool:
    return any(ECC_MARKER in h.get("command", "") for h in entry.get("hooks", []))


def split_settings(ecc_settings: dict) -> None:
    """Merge ECC hooks/keys into settings.local.json, replacing previous ECC hooks."""
    local_path = CLAUDE / "settings.local.json"
    local = load_json(local_path, {})

    hooks = {
        event: [e for e in entries if not is_ecc_hook(e)]
        for event, entries in local.get("hooks", {}).items()
    }
    for event, entries in ecc_settings.get("hooks", {}).items():
        hooks.setdefault(event, []).extend(entries)
    local["hooks"] = {k: v for k, v in hooks.items() if v}

    for key, value in ecc_settings.items():
        if key != "hooks":
            local.setdefault(key, value)

    write_json(local_path, local)
    log(f"ECC hooks written to {local_path.relative_to(REPO)}")


def managed_paths() -> list[str]:
    state = load_json(CLAUDE / "ecc" / "install-state.json", {"operations": []})
    rels = set()
    for op in state["operations"]:
        try:
            rels.add(Path(op["destinationPath"]).relative_to(CLAUDE).as_posix())
        except ValueError:
            continue
    rels.discard("settings.json")
    return sorted(rels)


def keep_name(rel: str, keep: dict) -> bool:
    parts = rel.split("/")
    if parts[0] == "agents" and len(parts) == 2:
        return Path(parts[1]).stem in keep["agents"]
    if parts[0] == "commands" and len(parts) == 2:
        return Path(parts[1]).stem in keep["commands"]
    if parts[0] == "skills" and len(parts) >= 2:
        return parts[1] in keep["skills"]
    if parts[:2] == [".agents", "skills"] and len(parts) >= 3:
        return parts[2] in keep["skills"]
    if parts[:2] == ["rules", "ecc"] and len(parts) >= 4:
        return parts[2] in keep["rules"]
    return True


def prune(paths: list[str], keep: dict) -> list[str]:
    kept, removed = [], 0
    for rel in paths:
        if keep_name(rel, keep):
            kept.append(rel)
            continue
        target = CLAUDE / rel
        if target.is_file() or target.is_symlink():
            target.unlink()
            removed += 1
    for base in ("agents", "commands", "skills", ".agents/skills", "rules/ecc"):
        root = CLAUDE / base
        if not root.is_dir():
            continue
        for d in sorted(root.rglob("*"), key=lambda p: len(p.parts), reverse=True):
            if d.is_dir() and not any(d.iterdir()):
                d.rmdir()
    log(f"pruned {removed} ECC files not in ecc-keep.json")
    return kept


def write_gitignore(kept: list[str]) -> None:
    dirs = ["ecc/", ".agents/", ".pi/", "scripts/", "hooks/", "mcp-configs/", "rules/ecc/"]
    lines = [
        "# Generated by scripts/ecc_sync.py - ECC-managed files are installed per machine.",
        "# Platform-owned files in this directory stay tracked.",
        "/settings.local.json",
        *(f"/{d}" for d in dirs),
    ]
    lines += [f"/{rel}" for rel in kept if not rel.startswith(tuple(dirs))]
    (CLAUDE / ".gitignore").write_text("\n".join(lines) + "\n")
    log("wrote .claude/.gitignore")


def main() -> int:
    ecc_home = resolve_ecc_home()
    log(f"using ECC at {ecc_home}")

    settings_path = CLAUDE / "settings.json"
    platform_settings = settings_path.read_text() if settings_path.is_file() else None
    if platform_settings is not None:
        settings_path.unlink()

    try:
        subprocess.run(
            [str(ecc_home / "install.sh"), "--config", str(REPO / "ecc-install.json"), "--enable-hooks"],
            cwd=REPO,
            check=True,
            stdout=subprocess.DEVNULL,
        )
        split_settings(load_json(settings_path, {}))
    finally:
        if platform_settings is not None:
            settings_path.write_text(platform_settings)
        elif settings_path.exists():
            settings_path.unlink()

    kept = prune(managed_paths(), load_json(REPO / "ecc-keep.json", {}))
    write_gitignore(kept)
    log("done")
    return 0


if __name__ == "__main__":
    sys.exit(main())
